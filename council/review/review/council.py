"""The council: the experts' relay on the engine, the notes for the person, the verdict and the dissent.

For a contract:
1. the split gives a section to each expert;
2. the engine's relay makes the experts think in order and the rapporteur write the verdict;
3. each expert writes its note from a copy of its own memory: the note does not enter the chain;
4. confidence from the logprobs and dissent between note and verdict, per category.
"""

from __future__ import annotations

import json
import time
from dataclasses import asdict, dataclass, field
from typing import TYPE_CHECKING

from engine import TELEPATHY, TEXT, Agent, Engine, Generation, Relay

from .categories import Benchmark
from .confidence import boolean_tokens, level, p_yes
from .prompts import expert_instructions, note, rapporteur_instructions, reading, verdict
from .quotes import check
from .schemas import max_tokens, note_schema, verdict_schema
from .split import split_contract

if TYPE_CHECKING:
    import torch

# Cap on the analyses the experts write in text mode. With the engine's default 512 tokens the calibration of 12/10
# truncated all of them (9 out of 9): text started at a disadvantage. Every review saves the tokens of each analysis,
# so the report counts the ones that still hit the cap.
MAX_ANALYSIS_TOKENS = 2048
RAPPORTEUR = "rapporteur"


@dataclass
class Written:
    """A note or a verdict: the JSON (None if it is not valid), the confidences and what it cost."""

    data: dict | None
    p_yes: dict[str, float]
    # Category → the quote appears word for word in the contract.
    quotes_found: dict[str, bool]
    tokens_read: int
    tokens_generated: int
    text: str

    @property
    def valid(self) -> bool:
        return self.data is not None


@dataclass
class Thoughts:
    """An expert's thoughts without its memory: label and hidden states of the latent steps, a few KB.

    They are enough for the relay to give those thoughts to the same expert on another contract (`thoughts_from`), the
    eval's "swapped thoughts" test.
    """

    label: dict
    states: torch.Tensor


@dataclass
class Dissent:
    category: str
    role: str
    type: str  # major: the expert says yes and the verdict no; minor: the opposite
    expert_confidence: str | None
    verdict_confidence: str | None


@dataclass
class Review:
    benchmark: str
    contract: str
    mode: str
    latent_steps: int
    model: str
    split: dict
    # The W_a realignment of the latent steps: off only in the diagnosis run.
    realign: bool = True
    notes: dict[str, Written] = field(default_factory=dict)
    verdict: Written | None = None
    dissents: list[Dissent] = field(default_factory=list)
    stopped: dict | None = None
    fingerprints: list[str] = field(default_factory=list)
    tokens_read: int = 0
    tokens_generated: int = 0
    latent_positions: int = 0
    seconds: float = 0.0
    # Text mode only: expert → tokens generated by its analysis.
    analyses: dict[str, int] = field(default_factory=dict)

    def as_dict(self) -> dict:
        return asdict(self)


def _written(generation: Generation, trues: list[int], falses: list[int], contract: str) -> Written:
    try:
        data = json.loads(generation.text)
    except json.JSONDecodeError:
        data = None
    return Written(
        data,
        p_yes(generation, trues, falses),
        check(data, contract),
        generation.tokens_read,
        generation.tokens_generated,
        generation.text,
    )


def _confidence(written: Written, key: str, position: bool) -> str | None:
    p = written.p_yes.get(key)
    return None if p is None else level(p, position)


def dissents(benchmark: Benchmark, notes: dict[str, Written], judgement: Written) -> list[Dissent]:
    """For each category, the note of the expert who looks at it against the verdict."""
    if not judgement.valid:
        return []
    found = []
    for category in benchmark.categories:
        expert = notes.get(category.role)
        if expert is None or not expert.valid:
            continue
        expert_says = expert.data["flag"].get(category.key)
        verdict_says = judgement.data["flag"].get(category.key)
        if expert_says is None or verdict_says is None or expert_says == verdict_says:
            continue
        found.append(
            Dissent(
                category.key,
                category.role,
                "major" if expert_says else "minor",
                _confidence(expert, category.key, expert_says),
                _confidence(judgement, category.key, verdict_says),
            )
        )
    return found


class Council:
    def __init__(
        self,
        engine: Engine,
        benchmark: Benchmark,
        *,
        mode: str = TELEPATHY,
        latent_steps: int = 10,
        translate: bool = False,
    ) -> None:
        self.engine = engine
        self.benchmark = benchmark
        self.mode = mode
        self.latent_steps = latent_steps
        self.translate = translate
        self.experts = [Agent(r, expert_instructions(r, benchmark)) for r in benchmark.readers]
        self.rapporteur = Agent(RAPPORTEUR, rapporteur_instructions(benchmark))
        self.trues, self.falses = boolean_tokens(engine.model.tokenizer)
        # The experts' thoughts in the last telepathy review, for the swapped-thoughts test.
        self.thoughts: dict[str, Thoughts] = {}

    def review(self, contract: str, text: str, **options) -> Review:
        """`options` go to the relay: for example `thoughts_from` for the “Pre-registered eval” test or `attacks` for the demo."""
        start = time.perf_counter()
        split = split_contract(text, self.benchmark.readers, self.benchmark.family)
        session = f"{self.benchmark.name}/{contract}/{self.mode}/m{self.latent_steps}"
        texts = {r: reading(split.sections[r]) for r in self.benchmark.readers}
        texts[RAPPORTEUR] = verdict(translate=self.translate)
        relay = Relay(self.engine, self.experts, self.rapporteur, mode=self.mode, latent_steps=self.latent_steps)
        schema = verdict_schema(self.benchmark.categories)
        outcome = relay.run(
            session,
            texts,
            schema=schema,
            field_order=True,
            max_spaces=1,
            observe=self.trues + self.falses,
            max_tokens=max_tokens(schema),
            **options,
        )
        review = Review(
            self.benchmark.name,
            contract,
            self.mode,
            self.latent_steps,
            self.engine.model.name,
            {
                "mode": split.mode,
                "clauses": len(split.clauses),
                "chars": {r: len(s) for r, s in split.sections.items()},
            },
            realign=self.engine.model.realign,
            fingerprints=[m.fingerprint for m in outcome.messages],
            latent_positions=outcome.latent_positions,
        )
        if self.mode == TEXT:
            review.analyses = {m.sender: m.label["tokens_generated"] for m in outcome.messages}
        self.thoughts = {
            m.sender: Thoughts(dict(m.label), m.states.to("cpu")) for m in outcome.messages if m.states is not None
        }
        if outcome.stopped is not None:
            review.stopped = asdict(outcome.stopped)
        else:
            review.verdict = _written(outcome.final, self.trues, self.falses, text)
        read, generated = outcome.tokens_read, outcome.tokens_generated
        for i, expert in enumerate(self.experts[: len(outcome.messages)]):
            # The note comes from a copy of the expert's memory and does not enter the chain.
            section = split.sections[expert.name] if self.mode == TEXT else None
            schema_of_note = note_schema(self.benchmark.of_role(expert.name))
            written = self.engine.write(
                expert,
                note(section),
                outcome.messages[: i + 1],
                mode=self.mode,
                schema=schema_of_note,
                field_order=True,
                max_spaces=1,
                observe=self.trues + self.falses,
                max_tokens=max_tokens(schema_of_note),
            )
            review.notes[expert.name] = _written(written, self.trues, self.falses, text)
            read, generated = read + written.tokens_read, generated + written.tokens_generated
        if review.verdict is not None:
            review.dissents = dissents(self.benchmark, review.notes, review.verdict)
        review.tokens_read, review.tokens_generated = read, generated
        review.seconds = time.perf_counter() - start
        return review
